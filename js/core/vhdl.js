(function (root, factory) {
  const isNode = typeof module !== 'undefined' && module.exports;
  const Circuit = isNode ? require('./circuit.js') : root.LGECircuit;
  const mod = factory(Circuit);
  if (isNode) module.exports = mod;
  else root.LGEVHDL = mod;
})(typeof self !== 'undefined' ? self : globalThis, function (Circuit) {
  'use strict';

  const KEYWORDS = new Set((
    'entity architecture port map signal begin end is of in out inout buffer linkage and or not xor nand nor xnor ' +
    'library use all process wait for loop if then else elsif when select with component generic constant variable ' +
    'type subtype array downto to work ieee std_logic std_logic_vector std_ulogic'
  ).split(' '));

  function sanitizeIdent(name, fallback) {
    let s = String(name == null ? '' : name).trim().replace(/[^A-Za-z0-9_]/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
    if (!s) s = fallback || 'x';
    if (/^[0-9]/.test(s)) s = '_' + s;
    if (KEYWORDS.has(s.toLowerCase())) s += '_';
    return s;
  }

  function dedupe(base, used) {
    let cand = base;
    let i = 2;
    while (used.has(cand.toLowerCase())) cand = base + '_' + i++;
    used.add(cand.toLowerCase());
    return cand;
  }

  function entityNameOf(circuit) {
    return sanitizeIdent((circuit.name || '').trim() || 'circuit', 'circuit');
  }

  function portNames(circuit, entityName) {
    const used = new Set([entityName.toLowerCase()]);
    const portOf = new Map();
    for (const c of circuit.components) {
      if (c.type === 'input' || c.type === 'pulse' || c.type === 'output' || c.type === 'screen') {
        portOf.set(c.id, dedupe(sanitizeIdent(c.label || c.id, 'p'), used));
      }
    }
    return portOf;
  }

  function signalNames(circuit, used) {
    const sigOf = new Map();
    for (const c of circuit.components) {
      if (Circuit.GATE_TYPES[c.type]) sigOf.set(c.id, dedupe(sanitizeIdent(c.id + '_y', 's'), used));
    }
    return sigOf;
  }

  function sourceExpr(circuit, portOf, sigOf, ref) {
    const p = Circuit.parseRef(ref);
    const c = Circuit.getComp(circuit, p[0]);
    if (!c) throw new Error('wire references unknown component ' + p[0]);
    if (c.type === 'input' || c.type === 'pulse') return portOf.get(p[0]);
    if (Circuit.GATE_TYPES[c.type]) return sigOf.get(p[0]);
    throw new Error('pin ' + ref + ' is not an output and cannot drive anything');
  }

  function gateExpr(circuit, portOf, sigOf, comp, wireAtTarget) {
    const g = Circuit.GATE_TYPES[comp.type];
    const arg = (pin) => {
      const w = wireAtTarget.get(comp.id + '.' + pin);
      return w ? sourceExpr(circuit, portOf, sigOf, w.from) : "'0'";
    };
    const a = arg(g.inputs[0]);
    if (g.inputs.length === 1) return 'not ' + a;
    const b = arg(g.inputs[1]);
    return a + ' ' + comp.type + ' ' + b;
  }

  function toVHDL(circuit) {
    const entityName = entityNameOf(circuit);
    const portOf = portNames(circuit, entityName);
    const used = new Set();
    for (const v of portOf.values()) used.add(v.toLowerCase());
    const sigOf = signalNames(circuit, used);
    const wireAtTarget = new Map(circuit.wires.map(w => [w.to, w]));

    const ports = [];
    for (const c of circuit.components) {
      if (c.type === 'input' || c.type === 'pulse') ports.push('    ' + portOf.get(c.id) + ' : in std_logic');
      else if (c.type === 'output') ports.push('    ' + portOf.get(c.id) + ' : out std_logic');
      else if (c.type === 'screen') ports.push('    ' + portOf.get(c.id) + ' : out std_logic_vector(3 downto 0)');
    }

    const sigs = [];
    const body = [];
    for (const c of circuit.components) {
      if (Circuit.GATE_TYPES[c.type]) {
        sigs.push('  signal ' + sigOf.get(c.id) + ' : std_logic;');
        body.push('  ' + sigOf.get(c.id) + ' <= ' + gateExpr(circuit, portOf, sigOf, c, wireAtTarget) + ';');
      }
    }
    for (const c of circuit.components) {
      if (c.type === 'output') {
        const w = wireAtTarget.get(c.id + '.a');
        body.push('  ' + portOf.get(c.id) + ' <= ' + (w ? sourceExpr(circuit, portOf, sigOf, w.from) : "'0'") + ';');
      } else if (c.type === 'screen') {
        for (let i = 0; i < 4; i++) {
          const w = wireAtTarget.get(c.id + '.i' + i);
          body.push('  ' + portOf.get(c.id) + '(' + i + ') <= ' + (w ? sourceExpr(circuit, portOf, sigOf, w.from) : "'0'") + ';');
        }
      }
    }

    const lines = [
      'library ieee;',
      'use ieee.std_logic_1164.all;',
      '',
      '-- Generated by Logic Gate Studio',
      'entity ' + entityName + ' is',
      '  port (',
      ports.length ? ports.join(';\n') + ';' : '',
      '  );',
      'end entity ' + entityName + ';',
      '',
      'architecture rtl of ' + entityName + ' is',
    ];
    if (sigs.length) lines.push(sigs.join('\n'));
    lines.push('begin');
    lines.push(body.join('\n'));
    lines.push('end architecture rtl;');
    lines.push('');
    return { entity: entityName, code: lines.join('\n') };
  }

  function toTestbench(circuit) {
    const entityName = entityNameOf(circuit);
    const tb = entityName + '_tb';
    const portOf = portNames(circuit, entityName);
    const inputs = circuit.components.filter(c => c.type === 'input' || c.type === 'pulse');

    const ports = [];
    for (const c of circuit.components) {
      if (c.type === 'input' || c.type === 'pulse') ports.push({ name: portOf.get(c.id), kind: 'std_logic' });
      else if (c.type === 'output') ports.push({ name: portOf.get(c.id), kind: 'std_logic' });
      else if (c.type === 'screen') ports.push({ name: portOf.get(c.id), kind: 'std_logic_vector(3 downto 0)' });
    }

    const L = [
      'library ieee;',
      'use ieee.std_logic_1164.all;',
      '',
      '-- Testbench generated by Logic Gate Studio: applies all input combinations',
      'entity ' + tb + ' is',
      'end entity ' + tb + ';',
      '',
      'architecture sim of ' + tb + ' is',
    ];
    for (const p of ports) {
      L.push('  signal ' + p.name + ' : ' + p.kind + ' := ' + (p.kind === 'std_logic' ? "'0'" : '"0000"') + ';');
    }
    L.push('begin');
    L.push('  dut : entity work.' + entityName + ' port map (');
    L.push(ports.map((p, i) => '    ' + p.name + ' => ' + p.name + (i < ports.length - 1 ? ',' : '')).join('\n'));
    L.push('  );');
    L.push('');
    L.push('  stim : process');
    L.push('  begin');
    const n = inputs.length;
    const combos = n <= 12 ? (1 << n) : 4096;
    for (let i = 0; i < combos; i++) {
      for (let b = 0; b < n; b++) {
        L.push("    " + portOf.get(inputs[b].id) + " <= '" + ((i >> b) & 1) + "';");
      }
      L.push('    wait for 10 ns;');
    }
    if (n > 12) L.push('    -- more than 12 inputs: only the first 4096 combinations are applied');
    L.push('    wait;');
    L.push('  end process;');
    L.push('end architecture sim;');
    L.push('');
    return { entity: tb, code: L.join('\n') };
  }

  function stripComments(s) {
    return s.replace(/--[^\n]*/g, '');
  }

  function sanitizeId(name) {
    let s = String(name).replace(/[^A-Za-z0-9_]/g, '_');
    if (!/^[A-Za-z_]/.test(s)) s = 'g_' + s;
    return s || 'g';
  }

  function fromVHDL(text) {
    const src = stripComments(String(text));

    const entityMatch = /\bentity\s+([A-Za-z]\w*)\s+is\b([\s\S]*?)\bend\s+entity\b/i.exec(src);
    if (!entityMatch) throw new Error('VHDL import: no "entity <name> is ... end entity" found');
    const entityName = entityMatch[1];
    const entityBody = entityMatch[2];

    const ports = [];
    const portMatch = /\bport\s*\(/i.exec(entityBody);
    let portBlock = null;
    if (portMatch) {
      const openIdx = portMatch.index + portMatch[0].length - 1;
      let depth = 0;
      for (let i = openIdx; i < entityBody.length; i++) {
        if (entityBody[i] === '(') depth++;
        else if (entityBody[i] === ')') {
          depth--;
          if (depth === 0) { portBlock = entityBody.slice(openIdx + 1, i); break; }
        }
      }
      if (portBlock === null) throw new Error('VHDL import: unbalanced parentheses in port clause');
    }
    if (portBlock !== null) {
      for (let decl of portBlock.split(';')) {
        decl = decl.trim();
        if (!decl) continue;
        const m = /^([A-Za-z]\w*)\s*:\s*(in|out|inout|buffer)\s+([\s\S]+)$/i.exec(decl);
        if (!m) throw new Error('VHDL import: unsupported port declaration: "' + decl + '"');
        const name = m[1];
        const mode = m[2].toLowerCase();
        const typ = m[3].trim().replace(/\s+/g, ' ');
        let kind = 'std_logic';
        let msb = null;
        let lsb = null;
        const vm = /^std_logic_vector\s*\(\s*(\d+)\s+downto\s+(\d+)\s*\)$/i.exec(typ);
        if (vm) {
          kind = 'vector';
          msb = +vm[1];
          lsb = +vm[2];
        } else if (!/^std_logic$/i.test(typ)) {
          throw new Error('VHDL import: unsupported port type "' + typ + '" (only std_logic and std_logic_vector(3 downto 0))');
        }
        ports.push({ name: name, mode: mode, kind: kind, msb: msb, lsb: lsb });
      }
    }

    const archMatch = /\barchitecture\s+[A-Za-z]\w*\s+of\s+[A-Za-z]\w*\s+is\b([\s\S]*?)\bbegin\b([\s\S]*?)\bend\s+architecture\b/i.exec(src);
    if (!archMatch) throw new Error('VHDL import: no "architecture <a> of <e> is ... begin ... end architecture" found');
    const archBody = archMatch[2];

    const stmts = archBody.split(';').map(s => s.trim()).filter(Boolean);
    const jobs = [];
    for (const st of stmts) {
      const m = /^([A-Za-z]\w*)\s*(?:\(\s*(\d+)\s*\))?\s*<=\s*([\s\S]+)$/.exec(st);
      if (!m) {
        throw new Error('VHDL import: unsupported statement (only concurrent assignments "lhs <= rhs;" are supported): "' + st.slice(0, 60) + '"');
      }
      jobs.push({ lhs: m[1], index: m[2] ? +m[2] : null, rhs: m[3].trim() });
    }

    const OPS = { and: 'and', or: 'or', xor: 'xor', nand: 'nand', nor: 'nor', xnor: 'xnor' };
    function classify(rhs) {
      const toks = rhs.split(/\s+/).filter(Boolean);
      if (toks.length === 1) {
        if (/^'[01xXzZ\-]'$/.test(toks[0])) return { kind: 'const' };
        return { kind: 'ref', name: toks[0] };
      }
      const first = toks[0].toLowerCase();
      if (first === 'not' && toks.length === 2) return { kind: 'unary', op: 'not', arg: toks[1] };
      if (toks.length === 3 && OPS[toks[1].toLowerCase()]) {
        return { kind: 'binary', op: OPS[toks[1].toLowerCase()], a: toks[0], b: toks[2] };
      }
      throw new Error('VHDL import: unsupported expression "' + rhs + '"');
    }

    const circuit = Circuit.createCircuit(entityName);
    const compByPort = new Map();
    for (const p of ports) {
      if (p.mode === 'in' || p.mode === 'inout') {
        const c = Circuit.addComponent(circuit, 'input', { label: p.name, value: 0 });
        compByPort.set(p.name.toLowerCase(), { comp: c, kind: 'input' });
      } else if (p.kind === 'vector') {
        if (p.msb !== 3 || p.lsb !== 0) {
          throw new Error('VHDL import: port ' + p.name + ' is std_logic_vector(' + p.msb + ' downto ' + p.lsb + '); only (3 downto 0) maps to the 4-bit screen');
        }
        const c = Circuit.addComponent(circuit, 'screen', { label: p.name });
        compByPort.set(p.name.toLowerCase(), { comp: c, kind: 'screen' });
      } else {
        const c = Circuit.addComponent(circuit, 'output', { label: p.name });
        compByPort.set(p.name.toLowerCase(), { comp: c, kind: 'output' });
      }
    }

    const usedIds = new Set(circuit.components.map(c => c.id));
    function newGateId(base) {
      const s = sanitizeId(base);
      let cand = s;
      let i = 2;
      while (usedIds.has(cand)) cand = s + '_' + i++;
      usedIds.add(cand);
      return cand;
    }

    const aliases = new Map();
    const exprBySignal = new Map();
    for (const j of jobs) {
      if (j.index !== null) continue;
      const e = classify(j.rhs);
      if (e.kind === 'ref') aliases.set(j.lhs.toLowerCase(), e.name);
      else exprBySignal.set(j.lhs.toLowerCase(), e);
    }

    const gateBySignal = new Map();
    for (const [sig, e] of exprBySignal) {
      const type = e.kind === 'unary' ? 'not' : e.op;
      const gid = newGateId(sig);
      const gc = Circuit.addComponent(circuit, type, { id: gid, label: sig });
      gateBySignal.set(sig, { comp: gc, expr: e });
    }

    function resolveRef(name) {
      let cur = name;
      let seen = 0;
      while (aliases.has(cur.toLowerCase()) && seen++ < 20) cur = aliases.get(cur.toLowerCase());
      const port = compByPort.get(cur.toLowerCase());
      if (port && port.kind === 'input') return port.comp.id + '.q';
      const g = gateBySignal.get(cur.toLowerCase());
      if (g) return g.comp.id + '.y';
      throw new Error('VHDL import: cannot resolve "' + name + '" to an input port or gate signal');
    }

    for (const [sig, g] of gateBySignal) {
      const e = g.expr;
      if (e.kind === 'unary') {
        Circuit.addWire(circuit, resolveRef(e.arg), g.comp.id + '.a');
      } else {
        Circuit.addWire(circuit, resolveRef(e.a), g.comp.id + '.a');
        Circuit.addWire(circuit, resolveRef(e.b), g.comp.id + '.b');
      }
    }

    let autoN = 0;
    for (const j of jobs) {
      const e = classify(j.rhs);
      if (e.kind === 'const') continue;
      const port = compByPort.get(j.lhs.toLowerCase());
      if (!port) continue;
      let srcRef;
      if (e.kind === 'ref') {
        srcRef = resolveRef(e.name);
      } else {
        const type = e.kind === 'unary' ? 'not' : e.op;
        const gid = newGateId('auto' + (++autoN));
        Circuit.addComponent(circuit, type, { id: gid, label: j.lhs + '_drv' });
        if (e.kind === 'unary') {
          Circuit.addWire(circuit, resolveRef(e.arg), gid + '.a');
        } else {
          Circuit.addWire(circuit, resolveRef(e.a), gid + '.a');
          Circuit.addWire(circuit, resolveRef(e.b), gid + '.b');
        }
        srcRef = gid + '.y';
      }
      if (port.kind === 'output') {
        Circuit.addWire(circuit, srcRef, port.comp.id + '.a');
      } else if (port.kind === 'screen') {
        if (j.index === null) throw new Error('VHDL import: assignment to vector port ' + j.lhs + ' needs a bit index, e.g. ' + j.lhs + '(0) <= ...;');
        if (j.index < 0 || j.index > 3) throw new Error('VHDL import: bit index ' + j.index + ' out of range for 4-bit screen port ' + j.lhs);
        Circuit.addWire(circuit, srcRef, port.comp.id + '.i' + j.index);
      }
    }

    Circuit.autoLayout(circuit);
    return circuit;
  }

  return {
    toVHDL: toVHDL,
    toTestbench: toTestbench,
    fromVHDL: fromVHDL,
    sanitizeIdent: sanitizeIdent,
  };
});
